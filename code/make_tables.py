"""Markdown tables for the paper from overlap results (CPU): all statistics, pooled and relation-stratified nulls.

Writes paper/tables/overlap_full.md. Cell format: observed median [95% CI] (null mean, z, one-sided p).
"""
from __future__ import annotations

import json
from pathlib import Path

RUNS = {"Llama-3.2-3B": "analysis/run_20261015_p3overlap_v2b_llama/results.json", "Gemma-2-2B": "analysis/run_20261015_p3overlap_v2c_gemma2/results.json"}
STATS = [("mlp_cosine", "MLP cosine"), ("mlp_spearman", "MLP Spearman"), ("resid_cosine", "residual cosine"), ("resid_spearman", "residual Spearman"),
         ("iou_top5", "IoU top-5"), ("iou_top10", "IoU top-10"), ("iou_top20", "IoU top-20")]
PAIRS = ["en-es", "en-hi", "es-hi"]


def cell(s: dict) -> str:
    z = "n/a" if s["z"] is None else f"{s['z']:.2f}"
    return f"{s['observed_median']:.3f} [{s['ci95'][0]:.3f}, {s['ci95'][1]:.3f}] (null {s['null_mean']:.3f}, z={z}, p={s['p_one_sided']:.3f})"


def main() -> None:
    out = ["# Overlap tables (generated by code/make_tables.py from the run artifacts)", ""]
    for model, path in RUNS.items():
        d = json.loads(Path(path).read_text(encoding="utf8"))["sets"]
        for key, title in (("primary_valid", "pooled shuffled-fact null"), ("primary_valid_stratified_by_relation", "relation-stratified null (post hoc for these two models)"),
                           ("valid_no_copyable", "pooled null, without event_year")):
            blk = d[key]
            out += [f"## {model}: {title} (n={blk['n_facts']})", "", "| statistic | " + " | ".join(p.upper() for p in PAIRS) + " |", "|---|" + "---|" * len(PAIRS)]
            for sk, name in STATS:
                out.append(f"| {name} | " + " | ".join(cell(blk["pairs"][p][sk]) for p in PAIRS) + " |")
            out.append("")
    Path("paper/tables").mkdir(parents=True, exist_ok=True)
    Path("paper/tables/overlap_full.md").write_text("\n".join(out), encoding="utf8")
    print("wrote paper/tables/overlap_full.md", len(out), "lines")


if __name__ == "__main__":
    main()
